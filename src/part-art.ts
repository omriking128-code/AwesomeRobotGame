import { PARTS } from './parts'

function icon(art: string): string[] {
  const rows = art
    .trim()
    .split('\n')
    .map((row) => row.trim())
  if (rows.length !== 16 || rows.some((row) => row.length !== 16)) {
    throw new Error(`icon must be 16x16\n${rows.map((row, index) => `${index} (${row.length}) ${row}`).join('\n')}`)
  }
  return rows
}

