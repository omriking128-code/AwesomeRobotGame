function line(name: string, index: number, chunks: string[]): string {
  if (chunks.length !== 4 || chunks.some((chunk) => chunk.length !== 8)) {
    throw new Error(`${name} row ${index} [${chunks.join('|')}]`)
  }
  return chunks.join('')
}

function sprite(name: string, rows: string[][]): string[] {
  return rows.map((chunks, index) => line(name, index, chunks))
}

